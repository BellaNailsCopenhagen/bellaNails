import type { Metadata } from "next"
import { notFound } from "next/navigation"
import { hasLocale, NextIntlClientProvider } from "next-intl"
import { getTranslations, setRequestLocale } from "next-intl/server"

import { QueryProvider } from "@/components/providers/query-provider"
import { Toaster } from "@/components/ui/sonner"
import { HideOnCheckout } from "@/components/layout/hide-on-checkout"
import { SiteHeader } from "@/components/layout/site-header"
import { SiteFooter } from "@/components/layout/site-footer"
import { routing } from "@/i18n/routing"
import { isProductionSite, SITE_URL } from "@/config/site"
import { fontVariables } from "@/config/fonts"
import "../globals.css"

// Pre-render both locales at build time (static, no per-request work).
export function generateStaticParams() {
  return routing.locales.map((locale) => ({ locale }))
}

export async function generateMetadata({
  params,
}: {
  params: Promise<{ locale: string }>
}): Promise<Metadata> {
  const { locale } = await params
  if (!hasLocale(routing.locales, locale)) {
    notFound()
  }
  const t = await getTranslations({ locale, namespace: "meta" })

  return {
    metadataBase: new URL(SITE_URL),
    // Belt and braces with robots.txt: a disallow stops a crawl, but a page
    // already known needs telling to drop it. Off the production host every
    // public page is noindex — a staging copy must not compete with the real
    // domain for the studio's own name.
    ...(isProductionSite() ? {} : { robots: { index: false, follow: false } }),
    title: {
      default: t("title"),
      template: "%s · Bella Nails",
    },
    description: t("description"),
    // Rich sharing cards (social/messaging apps). The OG image itself is
    // generated by [locale]/opengraph-image.tsx and auto-wired by Next.
    openGraph: {
      type: "website",
      siteName: "Bella Nails",
      title: t("title"),
      description: t("description"),
      locale: locale === "da" ? "da_DK" : "en_US",
    },
    twitter: {
      card: "summary_large_image",
      title: t("title"),
      description: t("description"),
    },
  }
}

export default async function LocaleLayout({
  children,
  params,
}: Readonly<{
  children: React.ReactNode
  params: Promise<{ locale: string }>
}>) {
  const { locale } = await params

  // Reject unknown locales (the proxy only routes da/en, but a direct hit on
  // e.g. /fr would otherwise render with the default locale).
  if (!hasLocale(routing.locales, locale)) {
    notFound()
  }

  // Opt this layout into static rendering for the resolved locale.
  setRequestLocale(locale)

  return (
    <html lang={locale} className={`${fontVariables} h-full antialiased`}>
      {/* suppressHydrationWarning: browser extensions (Grammarly et al.)
          inject attributes into <body> before React hydrates — harmless, and
          the suppression is attribute-only on this one element. */}
      <body className="min-h-full flex flex-col" suppressHydrationWarning>
        <QueryProvider>
          <NextIntlClientProvider>
            <SiteHeader />
            {children}
            <HideOnCheckout>
              <SiteFooter />
            </HideOnCheckout>
          </NextIntlClientProvider>
        </QueryProvider>
        <Toaster />
      </body>
    </html>
  )
}
